class TranslationHelper {
  /// Translates the input string based on the active locale.
  static String translate(BuildContext context, String text) {
    if (text.isEmpty) return text;
    
    String locale = 'en';
    try {
      locale = Provider.of<SettingsProvider>(context, listen: false).locale.languageCode;
    } catch (_) {
      try {
        locale = Localizations.localeOf(context).languageCode;
      } catch (_) {}
    }

    if (locale == 'en') return text;

    final cleanText = text.replaceAll('\n', ' ').trim().toLowerCase();

    // Short forms/acronyms that should remain untranslated in all languages:
    const shortForms = {
      'a.d': 'A.D',
      'ad': 'A.D',
      'n.c': 'N.C',
      'nc': 'N.C',
      'pocso': 'POCSO',
      'm.v': 'M.V',
      'm.v act': 'M.V. Act',
      'mv act': 'M.V. Act',
      'rti': 'RTI',
      'rit': 'RTI',
      'ndps': 'NDPS',
      'it': 'IT',
      'it act': 'IT Act',
      'mcoca': 'MCOCA',
      'uapa': 'UAPA',
      'vapa': 'UAPA',
      'mpda': 'MPDA',
      'cctns': 'CCTNS',
      'itsso': 'ITSSO',
      'nafis': 'NAFIS',
      'dar': 'DAR',
      'irda': 'IRDA',
      'fir': 'FIR',
      'bnss': 'BNSS',
      'hbt': 'HBT',
      'cbt': 'CBT',
    };

    if (shortForms.containsKey(cleanText)) {
      return shortForms[cleanText]!;
    }
    
    final langMap = _translations[locale];
    if (langMap != null && langMap.containsKey(cleanText)) {
      return langMap[cleanText]!;
    }

    // Dynamic checks for case count/record strings
    if (cleanText.endsWith(' cases') || cleanText.endsWith(' case')) {
      final parts = text.split(' ');
      if (parts.isNotEmpty) {
        final numberPart = parts[0];
        final label = cleanText.endsWith(' cases') ? 'cases' : 'case';
        final translatedLabel = translate(context, label);
        return '$numberPart $translatedLabel';
      }
    }
    if (cleanText.startsWith('showing: ')) {
      final target = text.substring('showing: '.length).trim();
      final translatedTarget = translate(context, target);
      final translatedShowing = translate(context, 'showing');
      final prefix = (translatedShowing != 'showing') ? translatedShowing : 'Showing';
      return '$prefix: $translatedTarget';
    }

    if (cleanText.endsWith(' records') || cleanText.endsWith(' record')) {
      final parts = text.split(' ');
      if (parts.isNotEmpty) {
        final numberPart = parts[0];
        final label = cleanText.endsWith(' records') ? 'records' : 'record';
        final translatedLabel = translate(context, label);
        return '$numberPart $translatedLabel';
      }
    }
    if (cleanText.endsWith(' form types') || cleanText.endsWith(' form type')) {
      final parts = text.split(' ');
      if (parts.isNotEmpty) {
        final numberPart = parts[0];
        final label = cleanText.endsWith(' form types') ? 'form types' : 'form type';
        final translatedLabel = translate(context, label);
        return '$numberPart $translatedLabel';
      }
    }
    if (cleanText.contains('registered')) {
      final parts = text.split(' ');
      if (parts.length >= 3) {
        final count = parts[0];
        final label = parts[1];
        final transLabel = translate(context, label);
        final transReg = translate(context, 'registered');
        return '$count $transLabel $transReg';
      }
    }

    return text;
  }

